"""
Этапы долгого ответа: что слой gemini рассказывает о себе наружу.

Ответ на реплику собирается не мгновенно и не за секунду: сжатие контекста - это
отдельный полноценный запрос к модели, а цикл повторов делает до cfg.max_retries попыток
с растущей паузой, суммарно до примерно восемнадцати минут. Все это время снаружи не
видно ничего, и бот в чате читается как зависший. Отсюда и модуль: рассказать, на каком
шаге бот сейчас находится.

Главное здесь - кому рассказывать. Про Telegram в karachur.gemini не знает никто, и
знать не должен, поэтому наружу уходит не готовая строка для чата, а структура Stage:
имя этапа и подробности к нему - номер попытки, сколько ждать, вид ошибки. Во что это
превратится в чате, решает karachur.tg.status, и у слоя gemini на этот счет нет мнения.
По той же причине причина повтора уезжает константой errors.ERROR_KIND_*, а не текстом:
переводить код ошибки на человеческий - тоже работа отображения, а не разговора с API.

Получатель необязателен. progress=None означает "рассказывать некому", и тогда report не
делает ничего: так работают тесты и любой не-телеграмный вызов, и добавление этапов ни
одного из них не касается.

Модуль зовется stages, а не progress: имя progress по всему пакету занято самим колбэком
(аргумент функций слоя gemini), и модуль под тем же именем перекрывался бы этим
аргументом внутри каждой такой функции.
"""

import logging
import typing

logger = logging.getLogger(__name__)

# Собираем историю чата и решаем, что из нее уедет в запрос.
CONTEXT = "context"
# Выгружаем вложения в Files API - на десятке файлов это надолго.
ATTACHMENTS = "attachments"
# Считаем точный размер контекста токенайзером: тоже запрос к API.
MEASURING = "measuring"
# Просим модель пересказать старую часть истории, чтобы освободить место.
COMPRESS = "compress"
# Ждем ответа на сам запрос.
ASKING = "asking"
# Предыдущая попытка не удалась, идем на следующую.
RETRY = "retry"
# Голосовое без триггера: нужна одна расшифровка, а не ответ.
TRANSCRIBE = "transcribe"


class Stage(typing.NamedTuple):
    """
    Один этап работы: что происходит сейчас и с какими подробностями.

    Поля намеренно общие на все этапы: number и total значат то номер попытки из общего
    числа, то номер прохода сжатия - что именно, ясно из name, и заводить под каждый
    этап свой набор полей было бы больше кода, чем пользы.

    :ivar name: одна из констант этого модуля
    :ivar number: номер текущего шага - попытки запроса или прохода сжатия
    :ivar total: сколько таких шагов всего отведено настройками
    :ivar delay: сколько секунд ждать перед следующей попыткой; None - ждать нечего
    :ivar error_kind: константа errors.ERROR_KIND_* - из-за чего идем на повтор;
        None - ошибки не было вовсе (например, модель вернула пустой текст)
    """

    name: str
    number: int | None = None
    total: int | None = None
    delay: float | None = None
    error_kind: str | None = None


# Получатель этапов: асинхронный вызываемый объект, которому их скармливают по одному.
Progress = typing.Callable[[Stage], typing.Awaitable[None]]


async def report(progress: Progress | None, stage: Stage):
    """
    Сообщает об этапе, если есть кому.

    Ошибка получателя гасится здесь намеренно, и это не перестраховка ради красоты.
    Рассказ о ходе дела - украшение, а ответ человеку - работа: заглушку могли удалить,
    чат закрыть, Telegram отбить правку по лимиту, и ни одна из этих мелочей не должна
    стоить готового ответа. Слой gemini не знает, кто на том конце колбэка, поэтому и не
    полагается на его аккуратность - свою беду получатель разбирает у себя (см.
    karachur.tg.status), а здесь стоит последняя сетка.

    :param progress: получатель этапов или None, если рассказывать некому
    :type progress: Progress | None
    :param stage: этап, о котором сообщаем
    :type stage: Stage
    """
    if progress is None:
        return
    try:
        await progress(stage)
    except Exception as e:  # pylint: disable=broad-exception-caught
        logger.warning("Не удалось сообщить об этапе %s: %s", stage.name, e)
